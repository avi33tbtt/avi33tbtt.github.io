const {
  Document, Packer, Paragraph, TextRun, HeadingLevel, Table, TableRow, TableCell,
  WidthType, ShadingType, BorderStyle
} = require("docx");

const P = (t, opts={}) => new Paragraph({ children: [new TextRun({ text: t, ...opts })], spacing: { after: 120 } });
const bullet = (t) => new Paragraph({ children: [new TextRun(t)], bullet: { level: 0 }, spacing: { after: 60 } });
const rule = () => new Paragraph({ text: "", border: { bottom: { color: "999999", space: 1, style: BorderStyle.SINGLE, size: 6 } }, spacing: { after: 200 } });

function cell(text, opts={}) {
  return new TableCell({
    width: { size: opts.width || 2500, type: WidthType.DXA },
    shading: opts.header ? { type: ShadingType.CLEAR, fill: "D9E2F3" } : undefined,
    children: [new Paragraph({ children: [new TextRun({ text, bold: !!opts.header })] })],
  });
}
function table(headers, rows, widths) {
  return new Table({
    columnWidths: widths,
    rows: [
      new TableRow({ children: headers.map((h, i) => cell(h, { header: true, width: widths[i] })) }),
      ...rows.map(r => new TableRow({ children: r.map((c, i) => cell(c, { width: widths[i] })) })),
    ],
  });
}

